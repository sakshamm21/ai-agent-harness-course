#!/usr/bin/env python3
"""Generate starter/ from solution/: every function whose docstring starts with "Part N:"
keeps its signature and docstring, and its body becomes raise NotImplementedError("Part N: ...").

    python3 scripts/make_starter.py          # rewrite starter/nanoharness/
    python3 scripts/make_starter.py --check  # exit 1 if starter/ is out of date
"""
from __future__ import annotations

import ast
import os
import re
import sys

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(PROJECT, "solution", "nanoharness")
DST = os.path.join(PROJECT, "starter", "nanoharness")
BANNER = "# STARTER: functions marked 'Part N' are yours to write. Generated by scripts/make_starter.py.\n"


def stub(source: str) -> str:
    tree = ast.parse(source)
    lines = source.splitlines(keepends=True)
    edits = []  # (first_line, last_line, replacement), 1-based inclusive
    for cls_or_mod in [tree] + [n for n in ast.walk(tree) if isinstance(n, ast.ClassDef)]:
        for node in cls_or_mod.body:
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            doc = ast.get_docstring(node) or ""
            m = re.match(r"Part (\d+):", doc)
            if not m or len(node.body) < 2:
                continue
            qual = node.name if cls_or_mod is tree else f"{cls_or_mod.name}.{node.name}"
            indent = " " * node.body[0].col_offset
            msg = f"Part {m.group(1)}: implement {qual} (see the docstring)"
            edits.append((node.body[1].lineno, node.end_lineno, f'{indent}raise NotImplementedError("{msg}")\n'))
    for first, last, text in sorted(edits, reverse=True):
        lines[first - 1:last] = [text]
    return BANNER + "".join(lines)


def main() -> int:
    check = "--check" in sys.argv
    os.makedirs(DST, exist_ok=True)
    stale = []
    for name in sorted(os.listdir(SRC)):
        if not name.endswith(".py"):
            continue
        with open(os.path.join(SRC, name), encoding="utf-8") as f:
            out = stub(f.read())
        dst = os.path.join(DST, name)
        current = open(dst, encoding="utf-8").read() if os.path.exists(dst) else None
        if current != out:
            stale.append(name)
            if not check:
                with open(dst, "w", encoding="utf-8") as f:
                    f.write(out)
    if check and stale:
        print("starter/ is out of date:", ", ".join(stale))
        return 1
    print(("checked" if check else "wrote") + f" {DST} ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
